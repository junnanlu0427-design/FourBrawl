        /// <summary>左右对称填格子：左边 c0~c1，右边镜像位置；传送带方向对调。</summary>
        static void M(byte[] b, int c0, int c1, int r0, int r1, byte v)
        {
            F(b, c0, c1, r0, r1, v);
            F(b, CC - 1 - c1, CC - 1 - c0, r0, r1, v == 5 ? (byte)6 : v == 6 ? (byte)5 : v);
        }
        /// <summary>出生点成对给出：(列, 脚下那一格的行)。先左后右，所以偶数号在左、奇数号在右。</summary>
        static int[][] Pairs(int cols, params int[] cr)
        {
            var l = new List<int[]>();
            for (int i = 0; i + 1 < cr.Length; i += 2)
            {
                l.Add(new[] { cr[i] * 20 + 10, cr[i + 1] * 20 - 2 });
                l.Add(new[] { (cols - 1 - cr[i]) * 20 + 10, cr[i + 1] * 20 - 2 });
            }
            return l.ToArray();
        }
